"""Generate CaseTable.g.cs: Unicode simple uppercase mapping (CO-12).

Spike shortcut: derived from CPython's unicodedata (Unicode 16.0). Python only
exposes full mappings, so a multi-character uppercase falls back to a
single-character titlecase (Greek iota subscripts), else the identity.
Production code should generate this from UnicodeData.txt field 12.
"""

import sys
import unicodedata

pairs = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    u = c.upper()
    if len(u) != 1:
        t = c.title()
        u = t if len(t) == 1 else c
    if ord(u) != cp:
        pairs.append((cp, ord(u)))

out = [
    "// <auto-generated> gen_case_table.py, Unicode "
    + unicodedata.unidata_version
    + " </auto-generated>",
    "static partial class CaseTable",
    "{",
    "    public static readonly int[] Pairs =",
    "    [",
]
for a, b in pairs:
    out.append(f"        0x{a:X}, 0x{b:X},")
out += ["    ];", "}", ""]
sys.stdout.write("\n".join(out))
